function countBlanks(text) {
  return (text.match(/_/g) || []).length;
}

const BLACK_CARDS = Object.freeze(
  BLACK_TEXTS.map((text, index) => {
    const pick = countBlanks(text);
    if (pick < 1 || pick > 2) {
      throw new Error("La carta negra debe tener 1 o 2 huecos: " + text);
    }
    return Object.freeze({
      id: "b" + String(index + 1).padStart(3, "0"),
      text,
      pick
    });
  })
);

